    /// <summary>
    /// An 8x8 bitmap font baked into a texture atlas. Glyphs are authored as
    /// ASCII art below so they stay human-readable. Only the characters the HUD
    /// needs are defined; everything else renders blank. Cell 127 is a solid
    /// white block used for filled quads (bars, panels, minimap cells).
    /// </summary>
    public sealed class Font
    {
        public const int Cell = 8;
        public const int Cols = 16;
        public const int Rows = 6;   // covers ASCII 32..127
        public const int AtlasW = Cols * Cell;   // 128
        public const int AtlasH = Rows * Cell;   // 48

        public readonly GlTexture Atlas;

        public Font()
        {
            var pm = new Pixmap(AtlasW, AtlasH);
            foreach (var kv in _glyphs)
            {
                int idx = kv.Key - 32;
                if (idx < 0 || idx >= Cols * Rows) continue;
                int cx = (idx % Cols) * Cell;
                int cy = (idx / Cols) * Cell;
                string[] rows = kv.Value;
                for (int y = 0; y < 8 && y < rows.Length; y++)
                    for (int x = 0; x < 8 && x < rows[y].Length; x++)
                        if (rows[y][x] != '.' && rows[y][x] != ' ')
                            pm.Set(cx + x, cy + y, 255, 255, 255, 255);
            }
            // solid block at cell 127
            int sidx = 127 - 32, sx = (sidx % Cols) * Cell, sy = (sidx / Cols) * Cell;
            pm.FillRect(sx, sy, Cell, Cell, 255, 255, 255, 255);

            Atlas = pm.ToTexture(true, false);
        }

        public void CellUV(char c, out float u0, out float v0, out float u1, out float v1)
        {
            int idx = c - 32;
            if (idx < 0 || idx >= Cols * Rows) idx = 0;
            int cx = idx % Cols, cy = idx / Cols;
            // inset by a hair to avoid bleeding into neighbours
            u0 = (cx * Cell + 0.05f) / AtlasW;
            v0 = (cy * Cell + 0.05f) / AtlasH;
            u1 = ((cx + 1) * Cell - 0.05f) / AtlasW;
            v1 = ((cy + 1) * Cell - 0.05f) / AtlasH;
        }

        /// <summary>True if the font has a glyph for <paramref name="c"/> (uppercase only).</summary>
        public static bool CanDraw(char c) => _glyphs.ContainsKey(c);

        public void SolidUV(out float u, out float v)
        {
            int idx = 127 - 32, cx = idx % Cols, cy = idx / Cols;
            u = (cx * Cell + 4f) / AtlasW;
            v = (cy * Cell + 4f) / AtlasH;
        }

